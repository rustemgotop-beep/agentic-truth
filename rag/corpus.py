def load_theorems_corpus() -> List[Dict[str, Any]]:
    """
    Загружает корпус теорем из внешнего файла data/theorems.json.
    Если файл отсутствует или некорректен, возвращает встроенный fallback-набор.
    """
    if os.path.exists(JSON_PATH):
        try:
            with open(JSON_PATH, "r", encoding="utf-8") as f:
                theorems = json.load(f)
                if isinstance(theorems, list) and len(theorems) > 0:
                    return theorems
        except Exception as e:
            print(f"⚠️ Ошибка загрузки {JSON_PATH}: {e}. Используется fallback-корпус.")
    return DEFAULT_SEED_CORPUS


# Загружаемый академический корпус теорем
MATH_SEED_CORPUS: List[Dict[str, Any]] = load_theorems_corpus()
