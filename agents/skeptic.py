from core.state import State


def skeptic_node(state: State):
    """[Member 3 — Skeptic / Red-Team Agent]"""
    print("\n🕵️ [Skeptic Agent] Проверяю доказательство Prover на логические скачки и контрпримеры...")

    query = state.get("query", "").lower()

    if "ролл" in query:
        gaps = [
            "Проверить дифференцируемость строго на открытом интервале (a, b), а не на замкнутом отрезке [a, b].",
            "Убедиться, что случай константной функции M = m разобран отдельно."
        ]
        counterexample = (
            "Контрпример при нарушении дифференцируемости: f(x) = |x| на [-1, 1]. "
            "Непрерывна на отрезке, f(-1) = f(1) = 1, но производная нигде не обращается в ноль (в нуле производная не существует)."
        )
    elif "лагранж" in query:
        gaps = [
            "Проверить корректность построения вспомогательной функции F(x).",
            "Убедиться, что деление на (b - a) корректно (отрезок ненулевой длины)."
        ]
        counterexample = (
            "Контрпример при разрыве производной: для f(x) = sgn(x) на [-1, 2] хорда существует, "
            "но ни в одной точке касательная ей не параллельна."
        )
    elif "предел" in query or "sin" in query:
        gaps = [
            "Убедиться, что угол x измеряется строго в радианах (в градусах предел равен π/180).",
            "Обосновать справедливость неравенства для отрицательных x через четность."
        ]
        counterexample = (
            "Замечание по размерностям: при аргументе в градусах lim sin(x°)/x = π/180 ≠ 1."
        )
    else:
        gaps = [
            "Проверить строгость перехода на границах отрезка [a, b].",
            "Убедиться, что явно оговорен случай нестрогого знакопостоянства."
        ]
        counterexample = (
            "Контрпример при нарушении непрерывности: для разрывной функции f(x) = sgn(x) на [-1, 1] "
            "при выколотом нуле f(0) = 1 условие разных знаков на концах выполнено, но нуля не существует."
        )

    con_report = (
        f"**Найденные потенциальные уязвимости:**\n"
        + "\n".join([f"- {g}" for g in gaps])
        + f"\n\n**Контрпример при ослаблении условий:**\n{counterexample}"
    )

    return {
        "logical_gaps": gaps,
        "counterexample": counterexample,
        "con_evidence": con_report
    }
