import os
from typing import Any
from langchain_core.language_models import FakeListLLM
from langchain_core.runnables import RunnableLambda
from core.config import config


def get_gigachat_llm(temperature: float = 0.1):
    """
    Фабрика языковой модели: строго GigaChat (Сбер).
    Автоматически инициализирует клиент GigaChat с корректными параметрами и scope.
    """
    credentials = config.gigachat_credentials
    scope = config.gigachat_scope
    model = config.gigachat_model

    if credentials:
        try:
            from langchain_gigachat.chat_models import GigaChat

            return GigaChat(
                credentials=credentials,
                verify_ssl_certs=config.verify_ssl_certs,
                scope=scope,
                model=model,
                base_url=config.gigachat_base_url,
                temperature=temperature,
                timeout=30.0
            )
        except Exception as e:
            print(f"⚠️ Ошибка инициализации GigaChat: {e}")

    # Fallback-режим для локальных тестов и демонстрации, если ключ еще не добавлен в .env
    print("ℹ️ Внимание: GIGACHAT_CREDENTIALS не найден в .env. Активирован локальный тестовый режим.")
    
    def mock_academic_responder(prompt_input: Any) -> str:
        prompt_str = prompt_input.to_string() if hasattr(prompt_input, "to_string") else str(prompt_input)
        p_lower = prompt_str.lower()

        # 1. Запрос на декомпозицию условий
        if "декомпозиции" in p_lower:
            if "ролл" in p_lower:
                return (
                    "- Функция $f(x)$ непрерывна на замкнутом отрезке $[a, b]$\n"
                    "- Функция $f(x)$ дифференцируема на открытом интервале $(a, b)$\n"
                    "- Значения функции на концах отрезка равны: $f(a) = f(b)$"
                )
            elif "лагранж" in p_lower:
                return (
                    "- Функция $f(x)$ непрерывна на замкнутом отрезке $[a, b]$\n"
                    "- Функция $f(x)$ дифференцируема на открытом интервале $(a, b)$"
                )
            elif "предел" in p_lower or "sin" in p_lower:
                return (
                    "- Аргумент $x$ выражен в радианах\n"
                    "- Точка $x_0 = 0$ является предельной точкой области определения ($x \\neq 0$)"
                )
            else:
                return (
                    "- Функция $f(x)$ непрерывна на замкнутом отрезке $[a, b]$\n"
                    "- Функция $f(x)$ принимает на концах отрезка значения разных знаков: $f(a) \\cdot f(b) < 0$\n"
                    "- Область определения функции связна и содержит отрезок $[a, b]$"
                )

        # 2. Запрос на код SymPy
        elif "sympy" in p_lower and "символьных вычислениях" in p_lower:
            if "ролл" in p_lower:
                return "sp.solve(sp.diff((x - a)*(b - x), x), x)"
            elif "лагранж" in p_lower:
                return "sp.diff(x**2, x)"
            elif "предел" in p_lower or "sin" in p_lower:
                return "sp.limit(sp.sin(x)/x, x, 0)"
            else:
                return "sp.solve(x - (a + b)/2, x)"

        # 3. Синтез полного доказательства
        else:
            if "ролл" in p_lower:
                return (
                    "### 1. Точная формулировка теоремы\n"
                    "**Теорема Ролля о нуле производной:**\n"
                    "Пусть функция $f(x)$ непрерывна на отрезке $[a, b]$, дифференцируема на интервале $(a, b)$ "
                    "и принимает равные значения на концах отрезка: $f(a) = f(b)$. "
                    "Тогда существует хотя бы одна точка $c \\in (a, b)$, такая что $f'(c) = 0$.\n\n"
                    "### 2. Условия применимости (Assumptions)\n"
                    "- $f(x) \\in C[a, b]$ (непрерывность на отрезке)\n"
                    "- $f(x) \\in D(a, b)$ (дифференцируемость на интервале)\n"
                    "- $f(a) = f(b)$ (равенство граничных значений)\n\n"
                    "### 3. Опорные леммы и теоретическая база\n"
                    "- Вторая теорема Вейерштрасса о достижении непрерывной функцией точных граней $M$ и $m$\n"
                    "- Лемма Ферма о равенстве нулю производной в точке локального экстремума\n\n"
                    "### 4. Пошаговое строгое доказательство\n"
                    "- **Шаг 1**: По второй теореме Вейерштрасса функция $f(x)$ непрерывна на компакте $[a, b]$, "
                    "следовательно, достигает своего максимума $M = \\max f(x)$ и минимума $m = \\min f(x)$.\n"
                    "- **Шаг 2 (Случай 1, $M = m$)**: Функция тождественно постоянна: $f(x) \\equiv const$. "
                    "Тогда $f'(x) = 0$ во всех точках интервала $(a, b)$, любая точка подходит в качестве $c$.\n"
                    "- **Шаг 3 (Случай 2, $M \\neq m$)**: Так как $f(a) = f(b)$, функция не может принимать оба экстремальных "
                    "значения только на концах отрезка. Значит, хотя бы одно из значений ($M$ или $m$) достигается во внутренней точке $c \\in (a, b)$.\n"
                    "- **Шаг 4**: Точка $c$ является точкой локального экстремума, лежащей внутри $(a, b)$. "
                    "По условию $f(x)$ дифференцируема в точке $c$. По лемме Ферма $f'(c) = 0$.\n"
                    "- **Заключение**: $\\blacksquare$ Существование стационарной точки доказано.\n\n"
                    "### 5. Формальная символьная проверка (SymPy Audit)\n"
                    "- Символьный движок SymPy подтвердил: на модельной функции параболы $f(x)=(x-a)(b-x)$ точка максимума $c = (a+b)/2$ строго лежит внутри $(a, b)$.\n\n"
                    "### 6. Первоисточники и цитаты (Grounded Evidence)\n"
                    "- Г.М. Фихтенгольц, «Курс дифференциального и интегрального исчисления», Т. 1, Гл. 4 («Теоремы о среднем», §102)."
                )
            elif "лагранж" in p_lower:
                return (
                    "### 1. Точная формулировка теоремы\n"
                    "**Теорема Лагранжа о конечном приращении:**\n"
                    "Если функция $f(x)$ непрерывна на отрезке $[a, b]$ и дифференцируема на интервале $(a, b)$, "
                    "то существует точка $c \\in (a, b)$, такая что:\n"
                    "$$f(b) - f(a) = f'(c)(b - a)$$\n\n"
                    "### 2. Условия применимости (Assumptions)\n"
                    "- $f(x) \\in C[a, b]$\n"
                    "- $f(x) \\in D(a, b)$\n\n"
                    "### 3. Опорные леммы и теоретическая база\n"
                    "- Теорема Ролля о нуле производной\n"
                    "- Свойства линейных комбинаций дифференцируемых функций\n\n"
                    "### 4. Пошаговое строгое доказательство\n"
                    "- **Шаг 1**: Введем вспомогательную функцию $F(x) = f(x) - f(a) - \\frac{f(b) - f(a)}{b - a}(x - a)$.\n"
                    "- **Шаг 2**: Проверим условия теоремы Ролля для $F(x)$: $F(a) = 0$ и $F(b) = 0$. Функция $F(x)$ непрерывна на $[a, b]$ и дифференцируема на $(a, b)$.\n"
                    "- **Шаг 3**: По теореме Ролля существует точка $c \\in (a, b)$, в которой $F'(c) = 0$.\n"
                    "- **Шаг 4**: Вычисляя производную: $F'(x) = f'(x) - \\frac{f(b) - f(a)}{b - a}$, откуда при $x = c$ получаем $f'(c) = \\frac{f(b) - f(a)}{b - a}$.\n"
                    "- **Заключение**: $\\blacksquare$ Формула конечных приращений доказана.\n\n"
                    "### 5. Формальная символьная проверка (SymPy Audit)\n"
                    "- Символьный расчет SymPy подтвердил обращение в нуль вспомогательной функции на границах.\n\n"
                    "### 6. Первоисточники и цитаты (Grounded Evidence)\n"
                    "- Л.Д. Кудрявцев, «Курс математического анализа», Т. 1."
                )
            elif "предел" in p_lower or "sin" in p_lower:
                return (
                    "### 1. Точная формулировка теоремы\n"
                    "**Первый замечательный предел:**\n"
                    "$$\\lim_{x \\to 0} \\frac{\\sin x}{x} = 1$$\n\n"
                    "### 2. Условия применимости (Assumptions)\n"
                    "- $x$ измеряется в радианах\n"
                    "- $x \\neq 0$, рассматривается проколотая окрестность точки $0$\n\n"
                    "### 3. Опорные леммы и теоретическая база\n"
                    "- Геометрическое определение тригонометрических функций на числовой окружности\n"
                    "- Теорема о предельном переходе в неравенствах (теорема о зажатой функции)\n\n"
                    "### 4. Пошаговое строгое доказательство\n"
                    "- **Шаг 1**: При $x \\in (0, \\pi/2)$ из сравнения площадей сектора и треугольников имеем: $\\sin x < x < \\tan x$.\n"
                    "- **Шаг 2**: Разделив на $\\sin x > 0$, получаем: $1 < \\frac{x}{\\sin x} < \\frac{1}{\\cos x}$, то есть $\\cos x < \\frac{\\sin x}{x} < 1$.\n"
                    "- **Шаг 3**: Поскольку $\\cos x$ и $\\frac{\\sin x}{x}$ четные, неравенство верно и для $x \\in (-\\pi/2, 0)$.\n"
                    "- **Шаг 4**: Так как $\\lim_{x \\to 0} \\cos x = 1$ и $\\lim_{x \\to 0} 1 = 1$, по теореме о зажатой функции предел равен $1$.\n"
                    "- **Заключение**: $\\blacksquare$ Первый замечательный предел доказан.\n\n"
                    "### 5. Формальная символьная проверка (SymPy Audit)\n"
                    "- SymPy: `sp.limit(sp.sin(x)/x, x, 0) = 1` подтверждено аналитически.\n\n"
                    "### 6. Первоисточники и цитаты (Grounded Evidence)\n"
                    "- В.А. Зорич, «Математический анализ», Ч. 1, Гл. 3."
                )
            else:
                return (
                    "### 1. Точная формулировка теоремы\n"
                    "Пусть функция $f(x)$ непрерывна на отрезке $[a, b]$ и принимает на его концах значения "
                    "разных знаков ($f(a) \\cdot f(b) < 0$). Тогда существует точка $c \\in (a, b)$, такая что $f(c) = 0$.\n\n"
                    "### 2. Условия применимости (Assumptions)\n"
                    "- $f(x) \\in C[a, b]$\n"
                    "- $f(a) \\cdot f(b) < 0$\n\n"
                    "### 3. Опорные леммы и теоретическая база\n"
                    "- Лемма о вложенных отрезках Коши-Кантора (принцип полноты действительных чисел)\n"
                    "- Определение непрерывности по Гейне/Коши\n\n"
                    "### 4. Пошаговое строгое доказательство\n"
                    "- **Шаг 1**: Рассматриваем отрезок $[a_0, b_0] = [a, b]$. Делим его точкой середины $x_0 = (a_0 + b_0)/2$.\n"
                    "- **Шаг 2**: Если $f(x_0) = 0$, теорема доказана ($c = x_0$). Если $f(x_0) \\neq 0$, выбираем ту половину, "
                    "на концах которой знаки различны. Обозначаем ее $[a_1, b_1]$.\n"
                    "- **Шаг 3**: Продолжая процесс дихотомии, получаем последовательность вложенных отрезков $[a_n, b_n]$, "
                    "длина которых $(b - a)/2^n \\to 0$.\n"
                    "- **Шаг 4**: По лемме Коши-Кантора существует единственная общая точка $c = \\lim a_n = \\lim b_n$.\n"
                    "- **Шаг 5**: В силу непрерывности $f(c) = \\lim f(a_n) \\le 0$ и $f(c) = \\lim f(b_n) \\ge 0$, следовательно, $f(c) = 0$.\n\n"
                    "### 5. Формальная символьная проверка (SymPy Audit)\n"
                    "- Символьное тождество и сходимость шага дихотомии проверены в SymPy.\n\n"
                    "### 6. Первоисточники и цитаты (Grounded Evidence)\n"
                    "- В.А. Зорич, «Математический анализ», Ч. 1, Гл. 4 (§2 «Свойства непрерывных функций»)."
                )

    return RunnableLambda(mock_academic_responder)


